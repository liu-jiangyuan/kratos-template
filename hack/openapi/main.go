// Command openapi post-processes the file emitted by protoc-gen-openapi:
//
//   - adds the OpenAPI servers block (protoc-gen-openapi does not emit one);
//   - wraps every 200 response in the template envelope {code, message, data};
//   - adds a default error response using the same envelope.
//
// Run it via `make openapi`; it is not part of the HTTP server.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"

	"gopkg.in/yaml.v3"
)

func main() {
	file := flag.String("file", "openapi.yaml", "OpenAPI file to post-process")
	serverURL := flag.String("server", "http://127.0.0.1:8000", "servers[0].url")
	serverDesc := flag.String("server-desc", "Local demo server", "servers[0].description")
	flag.Parse()

	raw, err := os.ReadFile(*file)
	if err != nil {
		fail("read %s: %v", *file, err)
	}
	var doc map[string]any
	if err := yaml.Unmarshal(raw, &doc); err != nil {
		fail("parse %s: %v", *file, err)
	}

	doc["servers"] = []any{
		map[string]any{
			"url":         *serverURL,
			"description": *serverDesc,
		},
	}

	schemas := ensureMap(ensureMap(doc, "components"), "schemas")
	schemas["Envelope"] = errorEnvelopeSchema()

	if paths, ok := doc["paths"].(map[string]any); ok {
		for _, item := range paths {
			pathItem, ok := item.(map[string]any)
			if !ok {
				continue
			}
			for _, op := range pathItem {
				operation, ok := op.(map[string]any)
				if !ok {
					continue
				}
				responses, ok := operation["responses"].(map[string]any)
				if !ok {
					continue
				}
				for status, response := range responses {
					if fmt.Sprint(status) != "200" {
						continue
					}
					resp, ok := response.(map[string]any)
					if !ok {
						continue
					}
					content := ensureMap(resp, "content")
					body := ensureMap(content, "application/json")
					if isEnvelope(body["schema"]) {
						continue
					}
					dataSchema := body["schema"]
					if dataSchema == nil {
						dataSchema = map[string]any{
							"type":        "object",
							"description": "Empty object.",
						}
					}
					body["schema"] = successEnvelopeSchema(nullableDataSchema(dataSchema))
				}
				if _, exists := responses["default"]; !exists {
					responses["default"] = map[string]any{
						"description": "Error envelope. Business errors use HTTP 200 with code=0; protocol/auth/system errors keep the real HTTP status with code=0.",
						"content": map[string]any{
							"application/json": map[string]any{
								"schema": map[string]any{
									"$ref": "#/components/schemas/Envelope",
								},
							},
						},
					}
				}
			}
		}
	}

	var buf bytes.Buffer
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(4)
	if err := enc.Encode(doc); err != nil {
		fail("encode %s: %v", *file, err)
	}
	if err := enc.Close(); err != nil {
		fail("close encoder: %v", err)
	}

	header := "# Generated by protoc-gen-openapi + hack/openapi post-processing\n" +
		"# Response bodies are wrapped in the template envelope {code, message, data}.\n\n"
	if err := os.WriteFile(*file, append([]byte(header), buf.Bytes()...), 0o644); err != nil {
		fail("write %s: %v", *file, err)
	}
}

func ensureMap(parent map[string]any, key string) map[string]any {
	if existing, ok := parent[key].(map[string]any); ok {
		return existing
	}
	created := make(map[string]any)
	parent[key] = created
	return created
}

func isEnvelope(schema any) bool {
	m, ok := schema.(map[string]any)
	if !ok {
		return false
	}
	props, ok := m["properties"].(map[string]any)
	if !ok {
		return false
	}
	_, hasCode := props["code"]
	_, hasMsg := props["message"]
	_, hasData := props["data"]
	return hasCode && hasMsg && hasData
}

// nullableDataSchema allows data to be null: a 200 response can also carry a
// business error (code=0) with data=null.
func nullableDataSchema(data any) any {
	m, ok := data.(map[string]any)
	if !ok {
		return data
	}
	if ref, ok := m["$ref"].(string); ok {
		return map[string]any{
			"nullable": true,
			"allOf": []any{
				map[string]any{"$ref": ref},
			},
		}
	}
	m["nullable"] = true
	return m
}

func successEnvelopeSchema(data any) map[string]any {
	return map[string]any{
		"type": "object",
		"properties": map[string]any{
			"code": map[string]any{
				"type":        "integer",
				"description": "1 = success; 0 = failure.",
				"example":     1,
			},
			"message": map[string]any{
				"type":        "string",
				"description": "Response message.",
				"example":     "success",
			},
			"data": data,
		},
		"required": []any{"code", "message", "data"},
	}
}

func errorEnvelopeSchema() map[string]any {
	return map[string]any{
		"type":        "object",
		"description": "Unified error envelope. Business errors use HTTP 200 with code=0; protocol/auth/system errors keep the real HTTP status with code=0.",
		"properties": map[string]any{
			"code": map[string]any{
				"type":        "integer",
				"description": "Always 0 for errors.",
				"example":     0,
			},
			"message": map[string]any{
				"type":        "string",
				"description": "Error message.",
				"example":     "invalid todo argument",
			},
			"data": map[string]any{
				"type":        "object",
				"nullable":    true,
				"description": "Null on failure.",
			},
		},
		"required": []any{"code", "message"},
	}
}

func fail(format string, args ...any) {
	fmt.Fprintf(os.Stderr, format+"\n", args...)
	os.Exit(1)
}
